#!/usr/bin/env bash
# Печатает в stdout всё содержимое usfc одним файлом: bootstrap из setup.sh
# плюс модули в порядке MODULES.
#
# Зачем: shellcheck на отдельном модуле не видит, что переменная читается
# из соседнего, и заваливает вывод ложными SC2034 — а в этом проекте
# межмодульные REPLY_*-переменные это осознанное соглашение (форк на каждую
# ячейку таблицы стоил бы секунд отрисовки). На сборке те же связи видны,
# и линтер отрабатывает без единого исключения в коде.
#
# Порядок здесь ровно тот же, что при загрузке в setup.sh, поэтому сборка —
# это буквально то, что выполняется на машине.
set -uo pipefail

ROOT="${1:-$(dirname "$0")/..}"
SRC="${ROOT}/src"

[ -f "${SRC}/MODULES" ] || { echo "нет ${SRC}/MODULES" >&2; exit 1; }

echo '#!/usr/bin/env bash'
# bootstrap: всё до блока загрузки модулей, без первой строки-шебанга
sed -n '2,/^# Загрузка модулей$/p' "${SRC}/setup.sh" | sed '$d;$d'

while IFS= read -r m; do
    case "$m" in ''|'#'*) continue ;; esac
    [ -f "${SRC}/${m}" ] || { echo "нет ${SRC}/${m}" >&2; exit 1; }
    cat "${SRC}/${m}"
done < "${SRC}/MODULES"
